interface CatalogTool {
  name: string;
  inputSchema: {type: string; properties: Record<string, Record<string, unknown>>; required?: string[]; additionalProperties?: boolean};
  outputSchema: {type: string; properties: Record<string, unknown>};
  annotations: {readOnlyHint: boolean; destructiveHint: boolean; idempotentHint: boolean; openWorldHint: boolean};
  _meta?: Record<string, unknown>;
}
interface RpcReply {
  result?: {tools?: CatalogTool[]; isError?: boolean; structuredContent?: Record<string, unknown>; content?: {type: string; text?: string; data?: string; mimeType?: string}[]};
  error?: {code: number; message: string};
}
const handlers: McpHttpHandler[] = [];
function rpcClient(env: Env, identity = OWNER) {
  const handler = createMcpHandler(() => createMediaServer(env, identity), {
    legacy: 'stateless', responseMode: 'auto', maxRequestBodySize: 13_398_872,
  });
  handlers.push(handler);
  return async (method: string, params: Record<string, unknown> = {}): Promise<RpcReply> => {
    const request = new Request(`${ORIGIN}/mcp`, {method: 'POST', headers: {
      'Content-Type': 'application/json', Accept: 'application/json, text/event-stream',
      'MCP-Protocol-Version': '2025-06-18',
    }, body: JSON.stringify({jsonrpc: '2.0', id: 1, method, params})});
    const response = await handler.fetch(request);
    expect(response.status).toBe(200);
    if (response.headers.get('Content-Type')?.includes('text/event-stream')) {
      const events = (await response.text()).replace(/\r\n/g, '\n').split('\n\n');
      const messages = events.flatMap(event => {
        const data = event.split('\n').filter(line => line.startsWith('data:')).map(line => line.slice(5).trimStart()).join('\n');
        return data ? [JSON.parse(data)] : [];
      });
      const message = messages.find(message => message.id === 1);
      expect(message).toBeDefined();
      return message as RpcReply;
    }
    return response.json() as Promise<RpcReply>;
  };
}
function encode(bytes: Uint8Array): string { return btoa(String.fromCharCode(...bytes)); }
function toolError(reply: RpcReply): {code: string; message: string} {
  expect(reply.result?.isError).toBe(true);
  const content = reply.result?.content?.find(part => part.type === 'text')?.text;
  expect(content).toBeTypeOf('string');
  return JSON.parse(content!).error;
}
afterEach(async () => {
  for (const handler of handlers.splice(0)) await handler.close();
  vi.unstubAllGlobals();
});

describe('actual MCP wire catalog', () => {
  it('advertises exactly six media tools with explicit input/output schemas', async () => {
    const {env, kv, namespace} = environment();
    const reply = await rpcClient(env)('tools/list');
    expect(reply.error).toBeUndefined();
    const tools = reply.result!.tools!;
    expect(tools.map(tool => tool.name).sort()).toEqual(['delete_media', 'download_media', 'get_media_metadata', 'list_media', 'upload_media', 'verify_media']);
    for (const tool of tools) {
      expect(tool.inputSchema.type).toBe('object');
      expect(tool.inputSchema.additionalProperties).toBe(false);
      expect(tool.outputSchema.type).toBe('object');
      expect(Object.keys(tool.outputSchema.properties).length).toBeGreaterThan(0);
      expect(tool.annotations.idempotentHint).toBe(true);
    }
    const byName = Object.fromEntries(tools.map(tool => [tool.name, tool]));
    expect(byName.upload_media!.annotations).toMatchObject({readOnlyHint: false, destructiveHint: false, openWorldHint: true});
    expect(byName.delete_media!.annotations).toMatchObject({readOnlyHint: false, destructiveHint: true});
    for (const name of ['download_media', 'verify_media', 'get_media_metadata', 'list_media']) {
      expect(byName[name]!.annotations).toMatchObject({readOnlyHint: true, destructiveHint: false});
    }
    expect(byName.upload_media!._meta?.['openai/fileParams']).toEqual(['file']);
    const file = byName.upload_media!.inputSchema.properties.file!;
    expect(Object.keys(file.properties as object).sort()).toEqual(['download_url', 'file_id', 'file_name', 'mime_type']);
    expect(file.required).toEqual(['download_url', 'file_id']);
    expect(byName.download_media!._meta?.securitySchemes).toEqual([{type: 'oauth2', scopes: ['media:read']}]);
    expect(byName.download_media!.annotations).toEqual({readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: false});
    expect(byName.delete_media!._meta?.securitySchemes).toEqual([{type: 'oauth2', scopes: ['media:read', 'media:delete']}]);
    expect(kv.list).not.toHaveBeenCalled();
    expect(namespace.getByName).not.toHaveBeenCalled();
  });
});


// MCP ImageContent is a genuine image content block; metadata remains separate.
describe('download_media MCP ImageContent', () => {
  it('returns an image block with original bytes and validated structured metadata', async () => {
    const {env, kv} = environment();
    const bytes = pngFixture(88);
    const digest = await sha256(bytes);
    const modified = '2026-11-07T00:00:00.000Z';
    kv.getWithMetadata.mockResolvedValueOnce({
      value: new ReadableStream({start(controller) {controller.enqueue(bytes); controller.close();}}),
      metadata: {contentType: 'image/png', sha256: digest, byteSize: bytes.length, etag: `"${digest}"`, uploadedAt: modified},
    });
    const rpc = rpcClient(env);
    const reply = await rpc('tools/call', {name: 'download_media', arguments: {key: KEY, expected_sha256: digest}});
    expect(reply.result?.isError).not.toBe(true);
    expect(reply.result?.structuredContent).toEqual({
      key: KEY, cdn_url: `https://cdn.phunghakorea.com${KEY}`, filename: 'test-v1-480.png',
      content_type: 'image/png', byte_size: bytes.length, sha256: digest,
      etag: `"${digest}"`, last_modified: modified,
    });
    const image = reply.result?.content?.find(part => part.type === 'image');
    expect(image?.mimeType).toBe('image/png');
    expect(image?.data).toBeTypeOf('string');
    expect(Buffer.from(image!.data!, 'base64')).toEqual(Buffer.from(bytes));
    expect(reply.result?.content?.some(part => part.type === 'text' && part.text === encode(bytes))).toBe(false);
    expect(kv.put).not.toHaveBeenCalled();
    expect(kv.delete).not.toHaveBeenCalled();
  });

  it('handles absent KV objects and enforces the read scope', async () => {
    const {env, kv} = environment();
    const rpc = rpcClient(env);
    expect(toolError(await rpc('tools/call', {name: 'download_media', arguments: {key: KEY}})).code).toBe('MEDIA_NOT_FOUND');
    const withoutRead = rpcClient(env, {...OWNER, scopes: []});
    expect(toolError(await withoutRead('tools/call', {name: 'download_media', arguments: {key: KEY}})).code).toBe('INSUFFICIENT_SCOPE');
    expect(kv.put).not.toHaveBeenCalled();
  });
});

describe('MCP tool permission and validation boundaries', () => {
  it('enforces write and delete scopes before reading input bytes or invoking bindings', async () => {
    const {env, kv, namespace} = environment();
    const rpc = rpcClient(env, {...OWNER, scopes: ['media:read']});
    const upload = await rpc('tools/call', {name: 'upload_media', arguments: {key: KEY, base64: 'invalid', content_type: 'image/png'}});
    expect(toolError(upload).code).toBe('INSUFFICIENT_SCOPE');
    const deletion = await rpc('tools/call', {name: 'delete_media', arguments: {key: KEY}});
    expect(toolError(deletion).code).toBe('INSUFFICIENT_SCOPE');
    expect(namespace.getByName).not.toHaveBeenCalled();
    expect(kv.getWithMetadata).not.toHaveBeenCalled();
  });

  it.each(['verify_media', 'get_media_metadata', 'list_media'])('requires the read scope for %s', async name => {
    const {env, kv} = environment();
    const rpc = rpcClient(env, {...OWNER, scopes: []});
    const reply = await rpc('tools/call', {name, arguments: name === 'list_media' ? {} : {key: KEY}});
    expect(toolError(reply).code).toBe('INSUFFICIENT_SCOPE');
    expect(kv.list).not.toHaveBeenCalled();
    expect(kv.getWithMetadata).not.toHaveBeenCalled();
  });

  it('rejects unsafe paths, mismatched extensions, and ambiguous sources before coordinator writes', async () => {
    const {env, namespace} = environment();
    const rpc = rpcClient(env);
    const base64 = encode(pngFixture());
    const inputs = [
      {arguments: {key: '/assets/../private.png', base64, content_type: 'image/png'}, code: 'INVALID_KEY'},
      {arguments: {key: '/assets/test-v1.webp', base64, content_type: 'image/png'}, code: 'EXTENSION_MISMATCH'},
      {arguments: {key: KEY, content_type: 'image/png'}, code: 'INVALID_SOURCE'},
      {arguments: {key: KEY, base64, file: {download_url: 'https://files.oaiusercontent.com/image', file_id: 'file-test'}, content_type: 'image/png'}, code: 'INVALID_SOURCE'},
    ];
    for (const input of inputs) {
      const reply = await rpc('tools/call', {name: 'upload_media', arguments: input.arguments});
      expect(toolError(reply).code).toBe(input.code);
    }
    expect(namespace.getByName).not.toHaveBeenCalled();
  });

  it('rejects non-allowlisted native file URLs without fetching or echoing signed URL details', async () => {
    const fetcher = vi.fn();
    vi.stubGlobal('fetch', fetcher);
    const {env, namespace} = environment();
    const reply = await rpcClient(env)('tools/call', {name: 'upload_media', arguments: {
      key: KEY, content_type: 'image/png', file: {file_id: 'file-test', download_url: 'https://127.0.0.1/image?token=test-private-value'},
    }});
    expect(reply.result?.isError).toBe(true);
    expect(JSON.stringify(reply)).not.toContain('test-private-value');
    expect(fetcher).not.toHaveBeenCalled();
    expect(namespace.getByName).not.toHaveBeenCalled();
  });

  it('applies schema validation before unsupported fields or MIME values reach a tool', async () => {
    const {env, namespace} = environment();
    const rpc = rpcClient(env);
    for (const args of [
      {key: KEY, base64: encode(pngFixture()), content_type: 'image/svg+xml'},
      {key: KEY, base64: encode(pngFixture()), content_type: 'image/png', secret: 'test-private-value'},
    ]) {
      const reply = await rpc('tools/call', {name: 'upload_media', arguments: args});
      expect(reply.result?.isError ?? !!reply.error).toBe(true);
      expect(JSON.stringify(reply)).not.toContain('test-private-value');
    }
    expect(namespace.getByName).not.toHaveBeenCalled();
  });

  it('passes real decoded image bytes to the single-key coordinator and returns structured metadata only', async () => {
    const {env, coordinator, namespace} = environment();
    const bytes = pngFixture(80);
    const reply = await rpcClient(env)('tools/call', {name: 'upload_media', arguments: {
      key: KEY, base64: encode(bytes), content_type: 'image/png',
    }});
    expect(reply.result?.isError).not.toBe(true);
    expect(namespace.getByName).toHaveBeenCalledWith(KEY);
    expect(coordinator.upload).toHaveBeenCalledWith(KEY, bytes, {content_type: 'image/png', etag: undefined, cache_control: undefined});
    expect(reply.result?.structuredContent).toMatchObject({key: KEY, cdn_url: `https://cdn.phunghakorea.com${KEY}`, byte_size: bytes.length, sha256: await sha256(bytes)});
    expect(JSON.stringify(reply)).not.toContain(encode(bytes));
  });

  it('redacts unexpected upstream exception text', async () => {
    const {env, coordinator} = environment();
    coordinator.upload.mockRejectedValueOnce(new Error('test-private-token; signed-url; image-payload'));
    const reply = await rpcClient(env)('tools/call', {name: 'upload_media', arguments: {
      key: KEY, base64: encode(pngFixture()), content_type: 'image/png',
    }});
    expect(toolError(reply).code).toBe('SERVICE_UNAVAILABLE');
    expect(JSON.stringify(reply)).not.toContain('test-private-token');
  });

  it('binds delete requests to the authenticated subject and rejects bulk arguments', async () => {
    const {env, coordinator} = environment();
    const rpc = rpcClient(env);
    const reply = await rpc('tools/call', {name: 'delete_media', arguments: {key: KEY}});
    expect(coordinator.deleteMedia).toHaveBeenCalledWith(KEY, OWNER.subject, undefined);
    expect(reply.result?.structuredContent).toMatchObject({deleted: false, status: 'confirmation_required'});
    const bulk = await rpc('tools/call', {name: 'delete_media', arguments: {keys: [KEY, '/assets/another.png']}});
    expect(bulk.result?.isError ?? !!bulk.error).toBe(true);
    expect(coordinator.deleteMedia).toHaveBeenCalledTimes(1);
  });
});

function confirmationUrl(query = ''): string {
  return `${ORIGIN}/authorize/delete?key=${encodeURIComponent(KEY)}&ticket=${TICKET}${query}`;
}
function formRequest(options: {origin?: string; cookie?: string; body?: string; contentType?: string} = {}): Request {
  return new Request(confirmationUrl(), {method: 'POST', headers: {
    Origin: options.origin ?? ORIGIN,
    Cookie: options.cookie ?? `__Host-media-delete=${CSRF}`,
    'Content-Type': options.contentType ?? 'application/x-www-form-urlencoded',
  }, body: options.body ?? new URLSearchParams({csrf: CSRF, decision: 'approve'}).toString()});
}

describe('owner deletion confirmation HTTP boundary', () => {
  it('only displays details on GET and sets a secure browser-bound CSRF cookie', async () => {
    const {env, coordinator} = environment();
    const response = await authorizeDelete(new Request(confirmationUrl()), OWNER, env);
    expect(response.status).toBe(200);
    expect(coordinator.approve).toHaveBeenCalledWith(KEY, TICKET, OWNER.subject, undefined);
    expect(coordinator.deleteMedia).not.toHaveBeenCalled();
    expect(response.headers.get('Set-Cookie')).toBe(`__Host-media-delete=${CSRF}; Secure; HttpOnly; SameSite=Strict; Path=/; Max-Age=600`);
    expect(response.headers.get('Content-Security-Policy')).toContain("frame-ancestors 'none'");
    expect(response.headers.get('Referrer-Policy')).toBe('same-origin');
    expect(response.headers.get('Cache-Control')).toBe('no-store');
    const html = await response.text();
    expect(html).toContain(KEY);
    expect(html).toContain('a'.repeat(64));
    expect(html).toContain('name="csrf"');
  });

  it('records approval only after same-origin POST with matching cookie/form CSRF', async () => {
    const {env, coordinator} = environment();
    const response = await authorizeDelete(formRequest(), OWNER, env);
    expect(response.status).toBe(200);
    expect(coordinator.approve).toHaveBeenCalledWith(KEY, TICKET, OWNER.subject, CSRF);
    expect(coordinator.deleteMedia).not.toHaveBeenCalled();
    expect(response.headers.get('Set-Cookie')).toContain('Max-Age=0');
    expect(await response.text()).toContain('Quay lại ChatGPT');
  });

  it.each([
    {origin: 'https://evil.example'},
    {origin: 'null'},
    {cookie: ''},
    {cookie: '__Host-media-delete=wrong'},
    {body: `csrf=${CSRF}&decision=deny`},
    {body: `csrf=${CSRF}&csrf=${CSRF}&decision=approve`},
    {body: 'decision=approve'},
    {contentType: 'text/plain'},
    {body: 'a'.repeat(4097)},
  ])('rejects forged or invalid approval POST %j', async options => {
    const {env, coordinator} = environment();
    const response = await authorizeDelete(formRequest(options), OWNER, env);
    expect(response.status).toBe(400);
    expect(coordinator.approve).not.toHaveBeenCalled();
    expect(coordinator.deleteMedia).not.toHaveBeenCalled();
  });

  it('rejects duplicate link parameters and methods other than GET/POST', async () => {
    const {env, coordinator} = environment();
    const duplicate = await authorizeDelete(new Request(confirmationUrl(`&ticket=${TICKET}`)), OWNER, env);
    expect(duplicate.status).toBe(400);
    const invalidMethod = await authorizeDelete(new Request(confirmationUrl(), {method: 'PUT'}), OWNER, env);
    expect(invalidMethod.status).toBe(405);
    expect(coordinator.approve).not.toHaveBeenCalled();
  });
});
